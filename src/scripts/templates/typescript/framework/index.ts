// The endpoint-authoring surface. Endpoints import from here and from
// `framework/validate.ts` — those two, and nowhere else inside `framework/`.
//
// The validator combinators are deliberately NOT re-exported here. A namespace
// re-export (`export * as v from "./validate.ts"`) materialises an object
// holding every validator, and esbuild then cannot prove any member unused: an
// endpoint that declares six validators ships all of them. Measured at 7-12 KB
// of unreachable code per bundle. Endpoints write
// `import * as v from "../../framework/validate.ts"` instead, which esbuild
// tree-shakes because every use is a static property access. Call sites are
// identical either way.
//
// Managed file — regenerated by `aic workspace update`.

