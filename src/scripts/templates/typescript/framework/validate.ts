export interface StringOptions {
  minLength?: number;
  maxLength?: number;
  /** Anchor it yourself; the validator does not add `^`/`$`. */
  pattern?: RegExp;
  /** Human wording for a pattern failure, e.g. `an ISO date (YYYY-MM-DD)`. */
  patternDescription?: string;
  description?: string;
}

export function string(options: StringOptions = {}): Validator<string> {
  const schema: JsonSchema = { type: "string" };
  if (options.minLength !== undefined) {
    schema["minLength"] = options.minLength;
  }
  if (options.maxLength !== undefined) {
    schema["maxLength"] = options.maxLength;
  }
  if (options.pattern !== undefined) {
    schema["pattern"] = options.pattern.source;
  }
  if (options.description !== undefined) {
    schema["description"] = options.description;
  }
  return define(schema, false, (input, path, issues) => {
    if (typeof input !== "string") {
      issue(issues, path, "expected a string");
      return "";
    }
    if (options.minLength !== undefined && input.length < options.minLength) {
      issue(
        issues,
        path,
        "must be at least " + options.minLength + " characters"
      );
    }
    if (options.maxLength !== undefined && input.length > options.maxLength) {
      issue(
        issues,
        path,
        "must be at most " + options.maxLength + " characters"
      );
    }
    if (options.pattern !== undefined && !options.pattern.test(input)) {
      const wanted =
        options.patternDescription ?? "match " + String(options.pattern);
      issue(issues, path, "must " + wanted);
    }
    return input;
  });
}

export interface NumberOptions {
  min?: number;
  max?: number;
  description?: string;
}

function numeric(integral: boolean, options: NumberOptions): Validator<number> {
  const schema: JsonSchema = { type: integral ? "integer" : "number" };
  if (options.min !== undefined) {
    schema["minimum"] = options.min;
  }
  if (options.max !== undefined) {
    schema["maximum"] = options.max;
  }
  if (options.description !== undefined) {
    schema["description"] = options.description;
  }
  return define(schema, false, (input, path, issues) => {
    let value: number;
    if (typeof input === "number") {
      value = input;
    } else if (typeof input === "string" && input.trim() !== "") {
      value = Number(input);
    } else {
      issue(
        issues,
        path,
        integral ? "expected an integer" : "expected a number"
      );
      return 0;
    }
    if (!isFinite(value)) {
      issue(
        issues,
        path,
        integral ? "expected an integer" : "expected a number"
      );
      return 0;
    }
    if (integral && Math.floor(value) !== value) {
      issue(issues, path, "expected an integer");
      return 0;
    }
    if (options.min !== undefined && value < options.min) {
      // IDM HTML-escapes every string in a thrown error, so `>=` would
      // reach the caller as `&#62;&#61;`. Keep messages to plain words.
      issue(issues, path, "must be at least " + options.min);
    }
    if (options.max !== undefined && value > options.max) {
      issue(issues, path, "must be at most " + options.max);
    }
    return value;
  });
}

export const integer = (options: NumberOptions = {}): Validator<number> =>
  numeric(true, options);

export const number = (options: NumberOptions = {}): Validator<number> =>
  numeric(false, options);

export function boolean(description?: string): Validator<boolean> {
  const schema: JsonSchema = { type: "boolean" };
  if (description !== undefined) {
    schema["description"] = description;
  }
  return define(schema, false, (input, path, issues) => {
    if (typeof input === "boolean") {
      return input;
    }
    if (input === "true") {
      return true;
    }
    if (input === "false") {
      return false;
    }
    issue(issues, path, "expected true or false");
    return false;
  });
}

/**
 * A closed set of string values. `const` type parameter inference makes the
 * handler see the literal union, not `string`:
 * `enumOf(["active", "retired"])` -> `Validator<"active" | "retired">`.
 */
export function enumOf<const T extends readonly string[]>(
  values: T,
  description?: string
): Validator<T[number]> {
  const schema: JsonSchema = { type: "string", enum: values.slice() };
  if (description !== undefined) {
    schema["description"] = description;
  }
  return define(schema, false, (input, path, issues) => {
    if (
      typeof input === "string" &&
      (values as readonly string[]).includes(input)
    ) {
      return input as T[number];
    }
    issue(issues, path, "must be one of: " + values.join(", "));
    return values[0] as T[number];
  });
}

/** A UUID-shaped string (any version, case-insensitive). */
export const uuid = (description?: string): Validator<string> =>
  string({
    pattern:
      /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/,
    patternDescription: "be a UUID",
    ...(description === undefined ? {} : { description }),
  });

/** A `YYYY-MM-DD` calendar date. */
export const isoDate = (description?: string): Validator<string> =>
  string({
    pattern: /^\d{4}-\d{2}-\d{2}$/,
    patternDescription: "be a date in YYYY-MM-DD form",
    ...(description === undefined ? {} : { description }),
  });

