/**
 * Validate a whole location (path params, query, headers) against `shape`,
 * reading raw values through `lookup` so a case-insensitive header map and a
 * plain query map can share this code. `lookup` returns `undefined` for absent.
 */
export function parseShape<S extends Shape>(
  shape: S,
  location: string,
  lookup: (key: string) => unknown,
  issues: Issue[]
): InferShape<S> {
  const out: Record<string, unknown> = {};
  for (const key of Object.keys(shape)) {
    const member = shape[key] as Validator<unknown>;
    const path = location + "." + key;
    const raw = lookup(key);
    if (raw === undefined && !member.isOptional) {
      issue(issues, path, "is required");
      continue;
    }
    out[key] = member.parse(raw, path, issues);
  }
  return out as InferShape<S>;
}
