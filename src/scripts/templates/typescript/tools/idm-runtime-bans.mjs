// Runtime bans the IDM script engine enforces, checked against the GENERATED
// bundle rather than the TypeScript source.
//
// The hand-written `.cjs` endpoints get these from `idm/eslint.config.js`. A
// bundle cannot go through that config — it would also have to satisfy
// `prettier/prettier` and `tsc`, neither of which is meaningful for generated
// output — so the same three bans are re-implemented here over the emitted
// file. The syntax rules make the endpoint fail to REGISTER; bare `Reflect`
// and `Proxy` references fail when executed because neither global exists.
//
// Sources: docs/api/11-idm-endpoints.md "Quirks", verified 2026-06-10.
//
// Managed file — regenerated by `aic workspace update`.

import { parse } from "@babel/parser";
import _traverse from "@babel/traverse";

const traverse = _traverse.default ?? _traverse;

const FUNCTION_TYPES = new Set([
  "FunctionDeclaration",
  "FunctionExpression",
  "ArrowFunctionExpression",
  "ObjectMethod",
  "ClassMethod",
  "ClassPrivateMethod",
]);

/**
 * @param {string} code generated bundle source
 * @returns {{ line: number, rule: string, message: string }[]}
 */
export function findRuntimeBanViolations(code) {
  const ast = parse(code, {
    sourceType: "script",
    tokens: true,
    allowReturnOutsideFunction: true,
  });
  const violations = [];
  const at = (node) => (node.loc ? node.loc.start.line : 0);

  traverse(ast, {
    ReferencedIdentifier(path) {
      const name = path.node.name;
      if (
        (name === "Reflect" || name === "Proxy") &&
        path.scope.getBinding(name) === undefined
      ) {
        violations.push({
          line: at(path.node),
          rule: "no-unsupported-global",
          message: "`" + name + "` is undefined on the IDM script engine",
        });
      }
    },
    enter(path) {
      const node = path.node;

      if (FUNCTION_TYPES.has(node.type)) {
        for (const param of node.params ?? []) {
          if (param.type === "AssignmentPattern") {
            violations.push({
              line: at(param),
              rule: "no-default-params",
              message:
                "default parameter value — the IDM script engine fails to compile it",
            });
          }
        }
      }

      // `for` keeps its initializer in `init`; `for-in`/`for-of` in `left`.
      if (
        node.type === "ForStatement" &&
        node.init?.type === "VariableDeclaration" &&
        node.init.kind === "const"
      ) {
        violations.push({
          line: at(node),
          rule: "no-const-loop-init",
          message:
            "`const` in a for-loop initializer — fails to compile on IDM",
        });
      }
      if (
        (node.type === "ForInStatement" || node.type === "ForOfStatement") &&
        node.left?.type === "VariableDeclaration" &&
        node.left.kind === "const"
      ) {
        violations.push({
          line: at(node),
          rule: "no-const-loop-init",
          message:
            "`const` in a for-in/for-of initializer — fails to compile on IDM",
        });
      }
    },
  });

  violations.push(...findTrailingParamCommas(ast));
  violations.sort((left, right) => left.line - right.line);
  return violations;
}

/**
 * A trailing comma in a function PARAMETER list is a compile failure (a
 * trailing comma in a CALL argument list is fine). The AST does not record it,
 * so this walks the token stream instead: the first token after the last
 * parameter must be `)`.
 */
function findTrailingParamCommas(ast) {
  const tokens = ast.tokens ?? [];
  const violations = [];

  const tokenAfter = (offset) => {
    let low = 0;
    let high = tokens.length - 1;
    let found = -1;
    while (low <= high) {
      const middle = (low + high) >> 1;
      if (tokens[middle].start >= offset) {
        found = middle;
        high = middle - 1;
      } else {
        low = middle + 1;
      }
    }
    return found < 0 ? null : tokens[found];
  };

  traverse(ast, {
    enter(path) {
      const node = path.node;
      if (!FUNCTION_TYPES.has(node.type)) {
        return;
      }
      const params = node.params ?? [];
      if (params.length === 0) {
        return;
      }
      const next = tokenAfter(params[params.length - 1].end);
      // Punctuator tokens carry their text on `type.label`, not on `value`.
      const text = next?.value ?? next?.type?.label;
      if (text === ",") {
        violations.push({
          line: next.loc ? next.loc.start.line : 0,
          rule: "no-trailing-param-comma",
          message:
            "trailing comma in a function parameter list — fails to compile on IDM",
        });
      }
    },
  });
  return violations;
}
