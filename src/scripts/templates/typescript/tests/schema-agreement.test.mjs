// `JSON.parse` so the key is a real own property; a `__proto__` in an object
// literal sets the prototype instead and the key never exists.
const PROTOTYPE_KEYS = [
  '{"__proto__":{"polluted":true}}',
  '{"constructor":1}',
  '{"hasOwnProperty":"x"}',
];

function schemaChecker(name, validator) {
  const uri = "https://aic.test/schema-agreement/" + encodeURIComponent(name);
  registerSchema(
    {
      $schema: "https://json-schema.org/draft/2020-12/schema",
      ...validator.schema,
    },
    uri
  );
  return validate(uri);
}

function parses(validator, value, mode) {
  const issues = [];
  const output = validator.parse(value, "x", issues, mode);
  return { ok: issues.length === 0, output };
}

const POOL = VALUES.concat(PROTOTYPE_KEYS.map((json) => JSON.parse(json)));

test("strict mode: schema and parser accept exactly the same values", async () => {
  const disagreements = [];
  for (const [name, validator] of CASES) {
    if (EXEMPT.has(name)) {
      continue;
    }
    const check = await schemaChecker(name, validator);
    for (const value of POOL) {
      const schemaOk = check(value).valid;
      const { ok: parserOk } = parses(validator, value, "strict");
      if (schemaOk !== parserOk) {
        disagreements.push(
          name +
            " " +
            JSON.stringify(value) +
            ": schema " +
            (schemaOk ? "accepts" : "rejects") +
            " but parser " +
            (parserOk ? "accepts" : "rejects")
        );
      }
    }
  }
  assert.deepEqual(disagreements, []);
});

test("coerce mode: everything the schema accepts, the parser accepts", async () => {
  // Not the reverse: coerce mode exists to turn the strings a path/query/header
  // value arrives as into the declared type, so the parser is deliberately wider.
  const rejected = [];
  for (const [name, validator] of CASES) {
    if (EXEMPT.has(name)) {
      continue;
    }
    const check = await schemaChecker(name + "#coerce", validator);
    for (const value of POOL) {
      if (!check(value).valid) {
        continue;
      }
      if (!parses(validator, value, "coerce").ok) {
        rejected.push(name + " " + JSON.stringify(value));
      }
    }
  }
  assert.deepEqual(rejected, []);
});

test("the property can fail — a divergent schema is caught", async () => {
  // Otherwise both assertions above could pass by never comparing anything.
  const honest = v.list(v.string(), { minItems: 2 });
  const divergent = {
    ...honest,
    schema: { type: "array", items: { type: "string" }, maxItems: 2 },
  };
  const check = await schemaChecker("mutant", divergent);
  const value = ["a"];
  assert.equal(
    check(value).valid,
    true,
    "the divergent schema accepts one item"
  );
  assert.equal(
    parses(divergent, value, "strict").ok,
    false,
    "while the parser still demands two"
  );
});

test("every exemption names a validator that exists", () => {
  const names = new Set(CASES.map(([name]) => name));
  for (const name of EXEMPT.keys()) {
    assert.ok(names.has(name), name + " is exempted but not exercised");
  }
});
