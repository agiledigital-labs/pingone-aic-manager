// The published schema and the enforced parser must agree.
//
// Every validator carries a JSON Schema fragment that the OpenAPI generator uses
// verbatim, and a `parse` the runtime enforces. Nothing checked them against each
// other: `validate.test.ts` asserts schema fragments case by case, so it catches
// the cases it happens to list and misses the rest. Mutation testing on
// 2026-08-19 confirmed the gap — publishing `maxItems` where the runtime enforces
// `minItems` passed type-check, lint, tests and build.
//
// The direction that matters is SCHEMA-ACCEPTS / PARSER-REJECTS: the document
// declares a request valid and the endpoint answers 400. The reverse, parser
// wider than schema, only under-documents what the endpoint would tolerate.
//
// So the property is asymmetric by mode:
//   strict  (JSON bodies, patch values, responses) — both directions must agree
//   coerce  (path, query, header: everything arrives as a string) — one direction,
//           because coercing "5" to 5 is the documented purpose of that mode
//
// Managed file — regenerated by `aic workspace update`.

import assert from "node:assert/strict";
import { test } from "node:test";

import { registerSchema, validate } from "@hyperjump/json-schema/draft-2020-12";

import * as v from "../framework/validate.ts";

// A validator whose accept-set the schema deliberately does not describe. Keep
// this list SHORT and give every entry a reason — each one is a place where a
// generated client and the endpoint disagree.
const EXEMPT = new Map([
  [
    "patchOperations()",
    // `request.patchOperations` is a Java list, mirrored over the wire as an
    // index-keyed object, so the parser accepts `{ "0": {...} }` as well as an
    // array while the schema documents the array (docs/api/11-idm-endpoints.md).
    // Parser wider than schema: no request is rejected by this.
    "accepts IDM's index-keyed mirror of a Java list",
  ],
]);

