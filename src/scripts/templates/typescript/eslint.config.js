// The one runtime hazard that must be caught in the source is subclassing
// `Error`: `Reflect` is undefined on IDM, so Babel's `_wrapNativeSuper` cannot
// restore the subclass prototype and `instanceof YourError` is silently false
// (probed 2026-08-13). Nothing downstream can detect that, so it is banned here.
//
// Managed file — regenerated by `aic workspace update`.

